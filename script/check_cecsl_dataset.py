import argparse
import gzip
import os
import pickle
from pathlib import Path

from paths import CE_CSL_ROOT, DATA_ROOT

DEFAULT_CECSL_ROOT = str(CE_CSL_ROOT)


def parse_args():
    parser = argparse.ArgumentParser(description="Check CE-CSL labels, videos, and pose files for Uni-Sign.")
    parser.add_argument(
        "--cecsl_root",
        default=os.environ.get("CE_CSL_ROOT", DEFAULT_CECSL_ROOT),
        help="Root path of the CE-CSL dataset.",
    )
    parser.add_argument(
        "--label_root",
        default=str(DATA_ROOT / "CE_CSL"),
        help="Converted label root generated by prepare_cecsl_labels.py",
    )
    parser.add_argument(
        "--video_subdir",
        default="video",
        help="Video directory under CE-CSL root.",
    )
    parser.add_argument(
        "--pose_subdir",
        default="pose_format",
        help="Pose directory under CE-CSL root.",
    )
    parser.add_argument("--splits", nargs="+", default=["train", "dev", "test"])
    parser.add_argument("--check_pose_content", action="store_true")
    return parser.parse_args()


def load_labels(label_path):
    with gzip.open(label_path, "rb") as f:
        return pickle.load(f)


def validate_pose_file(pose_path):
    try:
        with open(pose_path, "rb") as f:
            obj = pickle.load(f)
        if not isinstance(obj, dict):
            return False, "pose_not_dict"
        if "keypoints" not in obj or "scores" not in obj:
            return False, "pose_missing_keys"
        if len(obj["keypoints"]) == 0 or len(obj["scores"]) == 0:
            return False, "pose_empty"
        return True, "ok"
    except Exception as exc:
        return False, f"pose_load_error:{exc}"


def main():
    args = parse_args()
    cecsl_root = Path(args.cecsl_root)
    label_root = Path(args.label_root)
    video_root = cecsl_root / args.video_subdir
    pose_root = cecsl_root / args.pose_subdir

    overall_missing_videos = []
    overall_missing_pose = []
    overall_bad_pose = []

    for split in args.splits:
        label_path = label_root / f"labels.{split}"
        if not label_path.exists():
            print(f"[{split}] missing label file: {label_path}")
            continue

        labels = load_labels(label_path)
        print(f"[{split}] loaded labels: {len(labels)}")

        missing_videos = []
        missing_pose = []
        bad_pose = []

        for sample_name, sample in labels.items():
            video_rel = Path(sample["video_path"])
            video_path = video_root / video_rel
            pose_path = (pose_root / video_rel).with_suffix(".pkl")

            if not video_path.exists():
                missing_videos.append(str(video_path))

            if not pose_path.exists():
                missing_pose.append(str(pose_path))
            elif args.check_pose_content:
                is_ok, reason = validate_pose_file(pose_path)
                if not is_ok:
                    bad_pose.append((str(pose_path), reason))

        print(f"[{split}] missing videos: {len(missing_videos)}")
        print(f"[{split}] missing pose: {len(missing_pose)}")
        if args.check_pose_content:
            print(f"[{split}] bad pose: {len(bad_pose)}")

        overall_missing_videos.extend(missing_videos)
        overall_missing_pose.extend(missing_pose)
        overall_bad_pose.extend(bad_pose)

    print("summary:")
    print(f"missing videos total: {len(overall_missing_videos)}")
    print(f"missing pose total: {len(overall_missing_pose)}")
    if args.check_pose_content:
        print(f"bad pose total: {len(overall_bad_pose)}")

    if overall_missing_videos:
        print("sample missing videos:")
        for item in overall_missing_videos[:10]:
            print(item)

    if overall_missing_pose:
        print("sample missing pose:")
        for item in overall_missing_pose[:10]:
            print(item)

    if overall_bad_pose:
        print("sample bad pose:")
        for item, reason in overall_bad_pose[:10]:
            print(item, reason)


if __name__ == "__main__":
    main()
